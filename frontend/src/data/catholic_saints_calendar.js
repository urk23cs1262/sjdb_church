/**
 * Helper to get the Catholic Saint of the Day for any date object
 */
export function getSaintForDate(date = new Date()) {
  const monthStr = String(date.getMonth() + 1).padStart(2, '0');
  const dayStr = String(date.getDate()).padStart(2, '0');
  const key = `${monthStr}-${dayStr}`;

  // 1. Direct match for today's date
  if (CATHOLIC_SAINTS_CALENDAR[key]) {
    return CATHOLIC_SAINTS_CALENDAR[key];
  }

  // 2. Find the closest prior feast in the current month
  const keysInMonth = Object.keys(CATHOLIC_SAINTS_CALENDAR).filter(k => k.startsWith(monthStr));
  if (keysInMonth.length > 0) {
    const priorKeys = keysInMonth.filter(k => k <= key);
    const selectedKey = priorKeys.length > 0 ? priorKeys[priorKeys.length - 1] : keysInMonth[0];
    return CATHOLIC_SAINTS_CALENDAR[selectedKey];
  }

  // 3. General Catholic Fallback
  return {
    name: "St. Bernard of Clairvaux",
    nameTa: "கிளேர்வோ நகர் புனித பெர்னார்டு",
    description: "Celebrated Catholic saint and Doctor of the Church known for deep devotion to Jesus Christ and Mary.",
    descriptionTa: "இயேசு கிறிஸ்து மற்றும் அன்னை மரியா மீது ஆழ்ந்த பக்தி கொண்ட திருச்சபையின் சிறந்த புனிதர் மற்றும் மறைவல்லுநர்.",
    image: "https://upload.wikimedia.org/wikipedia/commons/thumb/a/a2/Bernard_of_Clairvaux_-_Google_Art_Project.jpg/500px-Bernard_of_Clairvaux_-_Google_Art_Project.jpg",
    link: "https://www.catholic.org/saints/sofd.php"
  };
}
